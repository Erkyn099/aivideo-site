const LANG_TO_HTML = { kz: 'kk', ru: 'ru' };

function applyLang(lang) {
  if (!I18N[lang]) return;

  document.documentElement.lang = LANG_TO_HTML[lang] || lang;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const value = I18N[lang][key];
    if (typeof value === 'string') el.textContent = value;
  });

  const titleStr = I18N[lang]['meta.title'];
  if (titleStr) document.title = titleStr;
  const descStr = I18N[lang]['meta.description'];
  const descEl = document.querySelector('meta[name="description"]');
  if (descEl && descStr) descEl.setAttribute('content', descStr);

  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('is-active', btn.dataset.lang === lang);
  });

  try { localStorage.setItem('lang', lang); } catch (e) {}
}

function initLangSwitch() {
  let initial = 'kz';
  try {
    const stored = localStorage.getItem('lang');
    if (stored && I18N[stored]) initial = stored;
  } catch (e) {}
  applyLang(initial);

  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', () => applyLang(btn.dataset.lang));
  });
}

// ===================== MOBILE MENU =====================
function initMobileMenu() {
  const burger = document.getElementById('burger');
  const nav = document.getElementById('nav');
  if (!burger || !nav) return;

  const close = () => {
    burger.classList.remove('is-open');
    nav.classList.remove('is-open');
    burger.setAttribute('aria-expanded', 'false');
  };

  burger.addEventListener('click', () => {
    const open = !burger.classList.contains('is-open');
    burger.classList.toggle('is-open', open);
    nav.classList.toggle('is-open', open);
    burger.setAttribute('aria-expanded', String(open));
  });

  nav.querySelectorAll('a').forEach(a => a.addEventListener('click', close));

  document.addEventListener('click', e => {
    if (nav.classList.contains('is-open') &&
        !nav.contains(e.target) &&
        !burger.contains(e.target)) {
      close();
    }
  });
}

// ===================== ORDER MODAL =====================
const WHATSAPP_NUMBER = '77074228257';

function initOrderModal() {
  const modal = document.getElementById('orderModal');
  const form = document.getElementById('orderForm');
  const pkgEl = document.getElementById('modalPkg');
  const nameInput = document.getElementById('orderName');
  if (!modal || !form) return;

  const open = (pkg) => {
    pkgEl.textContent = pkg || '';
    modal.classList.add('is-open');
    modal.setAttribute('aria-hidden', 'false');
    document.body.classList.add('modal-open');
    setTimeout(() => nameInput && nameInput.focus(), 150);
  };

  const close = () => {
    modal.classList.remove('is-open');
    modal.setAttribute('aria-hidden', 'true');
    document.body.classList.remove('modal-open');
  };

  document.querySelectorAll('[data-order]').forEach(btn => {
    btn.addEventListener('click', () => open(btn.dataset.order || ''));
  });

  modal.querySelectorAll('[data-close]').forEach(el => {
    el.addEventListener('click', close);
  });

  document.addEventListener('keydown', e => {
    if (e.key === 'Escape' && modal.classList.contains('is-open')) close();
  });

  form.addEventListener('submit', e => {
    e.preventDefault();
    if (!form.checkValidity()) {
      form.reportValidity();
      return;
    }
    const lang = (localStorage.getItem('lang') || 'kz');
    const t = I18N[lang] || I18N.kz;
    const name = nameInput.value.trim();
    const phone = document.getElementById('orderPhone').value.trim();
    const pkg = pkgEl.textContent.trim();

    const lines = [t['form.wa.intro']];
    if (pkg) lines.push(`${t['form.wa.pkg']}: ${pkg}`);
    lines.push(`${t['form.wa.name']}: ${name}`);
    lines.push(`${t['form.wa.phone']}: ${phone}`);

    const msg = encodeURIComponent(lines.join('\n'));
    const url = `https://wa.me/${WHATSAPP_NUMBER}?text=${msg}`;
    window.open(url, '_blank', 'noopener');
    close();
    form.reset();
  });
}

// ===================== STICKY HEADER STATE =====================
function initStickyHeader() {
  const header = document.getElementById('header');
  if (!header) return;
  const onScroll = () => header.classList.toggle('is-scrolled', window.scrollY > 8);
  onScroll();
  window.addEventListener('scroll', onScroll, { passive: true });
}

// ===================== REVEAL ON SCROLL =====================
function initReveal() {
  const els = document.querySelectorAll('.reveal');
  if (!('IntersectionObserver' in window)) {
    els.forEach(el => el.classList.add('is-visible'));
    return;
  }
  const io = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add('is-visible');
        io.unobserve(entry.target);
      }
    });
  }, { threshold: 0.12, rootMargin: '0px 0px -40px 0px' });
  els.forEach(el => io.observe(el));
}

// ===================== INIT =====================
document.addEventListener('DOMContentLoaded', () => {
  initLangSwitch();
  initMobileMenu();
  initOrderModal();
  initStickyHeader();
  initReveal();
});
